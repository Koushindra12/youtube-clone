export const getVideo = (id: string) => videos.find((v) => v.id === id) || videos[0];
export const getVideosByChannel = (channelId: string) => videos.filter((v) => v.channelId === channelId);
export const getShorts = () => videos.filter((v) => v.isShort);
export const getRegularVideos = () => videos.filter((v) => !v.isShort);
export const searchVideos = (query: string) => {
  const q = query.toLowerCase();
  return videos.filter(
    (v) =>
      v.title.toLowerCase().includes(q) ||
      v.channelName.toLowerCase().includes(q) ||
      v.tags.some((t) => t.toLowerCase().includes(q)) ||
      v.category.toLowerCase().includes(q)
  );
};
